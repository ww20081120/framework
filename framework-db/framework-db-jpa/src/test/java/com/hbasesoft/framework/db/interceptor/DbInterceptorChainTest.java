    @Order(2)
    static class SecondOrderedInterceptor extends RecordingInterceptor {

        /**
         * 构造 QUERY 型拦截器。
         *
         * @param trace 调用序记录
         */
        SecondOrderedInterceptor(final List<String> trace) {
            super(Set.of(DbOperationType.QUERY), ctx -> trace.add("second"));
        }
    }
